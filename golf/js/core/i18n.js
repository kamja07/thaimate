export function swapDom(root) {
  if (_lang !== 'en') return;
  root = root || document.body;
  const map = textMap.ko_en;
  // Text nodes
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
  const nodes = [];
  let n;
  while ((n = walker.nextNode())) nodes.push(n);
  for (const node of nodes) {
    const orig = node.nodeValue;
    if (!orig || !/[가-힣]/.test(orig)) continue;
    const trimmed = orig.trim();
    if (map[trimmed]) {
      node.nodeValue = orig.replace(trimmed, map[trimmed]);
    }
  }
  // Placeholders
  root.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
    const p = el.getAttribute('placeholder');
    if (p && map[p]) el.setAttribute('placeholder', map[p]);
  });
  // Button labels with only Korean (text + emoji)
  root.querySelectorAll('button, label').forEach(el => {
    // text-only children
    if (el.children.length === 0) {
      const t = el.textContent.trim();
      if (map[t]) el.textContent = map[t];
    }
  });
}



// ============ 자동 swap (Mutation Observer) ============
let _autoSwapObserver = null;

export function setupAutoSwap() {
  if (typeof MutationObserver === 'undefined') return;
  if (_autoSwapObserver) return;
  let _swapDebounceTimer = null;
  const _pendingNodes = new Set();
  _autoSwapObserver = new MutationObserver((mutations) => {
    if (getLang() !== 'en') return;
    for (const m of mutations) {
      for (const node of m.addedNodes) {
        if (node.nodeType === 1) _pendingNodes.add(node);
      }
    }
    if (_swapDebounceTimer) return;
    _swapDebounceTimer = setTimeout(() => {
      _swapDebounceTimer = null;
      const nodes = [..._pendingNodes];
      _pendingNodes.clear();
      for (const n of nodes) {
        try { swapDom(n); } catch (e) {}
      }
    }, 100);
  });
  _autoSwapObserver.observe(document.body, { childList: true, subtree: true });
}

export function teardownAutoSwap() {
  if (_autoSwapObserver) { _autoSwapObserver.disconnect(); _autoSwapObserver = null; }
}
