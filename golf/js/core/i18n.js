let _lang = 'ko';
try {
  const saved = localStorage.getItem('gd_lang');
  if (saved === 'ko' || saved === 'en') _lang = saved;
} catch(_) {}

export function t(key, vars) {
  let str = (translations[_lang] && translations[_lang][key]) || translations.ko[key] || key;
  if (vars) {
    for (const k in vars) {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    }
  }
  return str;
}

export function setLang(lang) {
  if (lang !== 'ko' && lang !== 'en') return false;
  _lang = lang;
  try { localStorage.setItem('gd_lang', lang); } catch(_) {}
  return true;
}

export function getLang() { return _lang; }

